def sanitize_task(task: str, title: str, family: str) -> str:
    """Keep the English task record while removing stale workspace locators."""
    task = task.replace("\r\n", "\n").replace("\r", "\n")
    task = re.sub(r"(?m)^\s{4}(?:gpu-run|bash|python3?).*$", "    [Original benchmark command omitted.]", task)

    def code_span(match):
        value = match.group(1)
        if re.search(
            r"(?i)(?:^/|(?:^|/)(?:repo|solution|profiles?|scripts|bench_results|benchmarks)(?:/|$)|"
            r"\.(?:py|md|csv|jsonl|sh):\d+$)",
            value,
        ):
            return "`[original task locator omitted]`"
        return match.group(0)

    task = re.sub(r"`([^`]+)`", code_span, task)
    task = re.sub(
        r"(?i)(?:/workspace/[^\s),;]+|(?:repo|solution|profiles?|scripts|bench_results|benchmarks)/[^\s),;]+)",
        "[original workspace locator omitted]",
        task,
    )
    task = re.sub(
        r"(?i)\b(?:repo|solution|profiles?|scripts|bench_results|benchmarks)/",
        "[original workspace locator omitted]",
        task,
    )
    task = re.sub(r"\n{3,}", "\n\n", task).strip() + "\n"
    header = (
        "<!-- Local transcription: operational source-workspace locators were omitted. -->\n"
        f"<!-- Task family: {family}; original English title: {title} -->\n\n"
    )
    return header + task


def correctness_record(task: str, performance_block: str) -> tuple[str, str]:
    explicit_patterns = (
        r"[^.\n]*(?:\d+/\d+ workloads pass correctness|all workloads pass(?:ing)? correctness|"
        r"correctness green)[^.\n]*[.]?",
    )
    for pattern in explicit_patterns:
        match = re.search(pattern, performance_block, re.IGNORECASE)
        if match:
            excerpt = clean_excerpt(match.group(0).strip())
            if excerpt:
                return "explicit-pass", excerpt
    gate = re.search(r"[^.\n]*correctness[^.\n]*[.]?", task, re.IGNORECASE)
    if gate:
        value = sanitize_task(gate.group(0).strip(), "correctness gate", "local").split("\n\n", 1)[-1].strip()
        return "gate-described-no-explicit-result", value
    return "", ""


def parse_evidence(row: dict, raw: bytes) -> tuple[dict | None, str | None]:
    try:
        text, evidence_mode = normalized_text(raw)
    except UnicodeDecodeError:
        return None, "evidence_not_utf8"
    metadata = parse_metadata(text)
    if metadata.get("Task family") != row.get("task_family"):
        return None, "manifest_metadata_task_family_mismatch"
    if metadata.get("Run") != row.get("run_path"):
        return None, "manifest_metadata_run_mismatch"
    if metadata.get("Compared source file") != row.get("selected_code_path"):
        return None, "manifest_metadata_code_path_mismatch"

    task = task_section(text)
    before_lang, before = fenced_section(text, "Complete code before optimization")
    after_lang, after = fenced_section(text, "Complete code after optimization")
    _diff_lang, imported_diff = fenced_section(text, "Complete unified diff")
    if None in (task, before, after, imported_diff):
        return None, "missing_required_evidence_section"
    if not before.strip():
        return None, "empty_before_source"
    if not after.strip():
        return None, "empty_after_source"
    if before == after:
        return None, "identical_before_after_source"
    if TRACE_LOCATOR_RE.search(before) or TRACE_LOCATOR_RE.search(after):
        return None, "source_contains_external_locator"

    title_match = re.match(r"^# Verified Optimization Evidence:\s*(.+)$", text)
    title = title_match.group(1).strip() if title_match else str(row.get("title", "")).strip()
    if title != row.get("title"):
        return None, "manifest_evidence_title_mismatch"
    if any(ord(character) > 127 for character in title):
        return None, "non_english_canonical_task"
    if row.get("task_family") == "cuda_cpp" and re.search(r"CuTe-DSL only|entirely in CuTe", task, re.IGNORECASE):
        if re.search(r"torch\.utils\.cpp_extension|\.cu[\"']", before + after):
            return None, "language_evidence_inconsistent"

    logical_name = Path(str(row["selected_code_path"])).name
    code_suffix = Path(logical_name).suffix.lower()
    if code_suffix not in SUPPORTED_CODE_SUFFIXES:
        return None, "unsupported_code_suffix"
    before_name = f"before{code_suffix}"
    after_name = f"after{code_suffix}"
    imported_expected = generated_diff(before, after, str(row["selected_code_path"]))
    if trim_diff(imported_diff) != trim_diff(imported_expected):
        return None, "imported_diff_inconsistent"
    local_diff = generated_diff(before, after, before_name=before_name, after_name=after_name)

    comparisons, raw_comparison_count = parse_performance(text)
    if not comparisons:
        return None, "no_direct_before_after_comparison"

    architectures = detect_architectures(f"{title}\n{task}")
    if not architectures:
        return None, "architecture_not_explicit"
    languages = detect_languages(title, before + after)
    if not languages:
        return None, "language_not_explicit"

    performance_block = section(text, "Verified performance evidence") or ""
    correctness_status, correctness_detail = correctness_record(task, performance_block)
    if not correctness_status:
        return None, "missing_correctness_gate"

    techniques = []
    for item in row.get("techniques") or []:
        mapped = TECHNIQUE_MAP.get(item)
        if not mapped:
            return None, "unmapped_technique"
        if mapped not in techniques:
            techniques.append(mapped)

    family = row["task_family"]
    kernel_types = FAMILY_KERNEL_TYPES.get(family)
    if not kernel_types:
        return None, "unmapped_task_family"
    hardware = detect_hardware(f"{task}\n{before}\n{after}")
    task_local = sanitize_task(task, title, family)
    if TRACE_LOCATOR_RE.search(task_local):
        return None, "task_locator_sanitization_failed"

    why = section(text, "Why the optimized version is faster") or ""
    observed = []
    for line in why.splitlines():
        match = re.match(r"^- \*\*Code change:\*\*\s*(.+)$", line)
        if match and not TRACE_LOCATOR_RE.search(match.group(1)):
            observed.append(match.group(1).strip())

    return {
        "text": text,
        "evidence_mode": evidence_mode,
        "evidence_sha256": sha256_bytes(text.encode("utf-8")),
        "task": task_local,
        "before": before,
        "after": after,
        "diff": local_diff,
        "language_fence": before_lang or after_lang or "python",
        "title": title,
        "architectures": architectures,
        "languages": languages,
        "dtype": detect_dtype(title, task),
        "techniques": techniques,
        "hardware_features": hardware,
        "kernel_types": kernel_types,
        "comparisons": comparisons,
        "raw_comparison_count": raw_comparison_count,
        "correctness_status": correctness_status,
        "correctness_detail": correctness_detail,
        "observed_changes": observed,
        "logical_code_name": logical_name,
        "before_name": before_name,
        "after_name": after_name,
    }, None


def logical_ids(row: dict, parsed: dict, manifest_sha: str) -> tuple[str, str]:
    run_sha = sha256_bytes(str(row["run_path"]).encode("utf-8"))[:16]
    logical_run_id = f"run-{run_sha}"
    identity = "\0".join(
        [
            row["task_family"],
            logical_run_id,
            row["selected_code_path"],
            parsed["evidence_sha256"],
        ]
    )
    suffix = sha256_bytes(identity.encode("utf-8"))[:16]
    experiment_id = f"experiment-{row['task_family'].replace('_', '-')}-{suffix}"
    return logical_run_id, experiment_id


def family_page_ids(family: str) -> tuple[str, str]:
    """Return human-facing aggregate IDs while bundles retain hashed identity."""
    slug = family.replace("_", "-")
    return f"experiment-family-{slug}", f"kernel-trace-{slug}"


def evidence_limitations(row: dict, parsed: dict) -> list[str]:
    limitations = [
        "The local corpus preserves the selected comparison, not the complete session trace.",
        "Causal mechanisms are hypotheses unless explicitly attributed by the retained evidence.",
    ]
    if parsed["correctness_status"] == "gate-described-no-explicit-result":
        limitations.append(
            "The retained comparison has no separate correctness result; the applicable task gate is documented."
        )
    if row.get("unreplayed_mutations"):
        limitations.append(
            f"The manifest reports {int(row['unreplayed_mutations'])} unreplayed mutation(s) outside the selected complete source pair."
        )
    if parsed["raw_comparison_count"] > len(parsed["comparisons"]):
        limitations.append(
            "Performance snippets that did not prove a direct positive old-to-new comparison were omitted."
        )
    return limitations


