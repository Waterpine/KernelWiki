def bundle_files(
    row: dict,
    parsed: dict,
    logical_run_id: str,
    source_id: str,
    wiki_id: str,
    manifest_sha: str,
    artifact_dir: str,
    limitations: list[str],
) -> dict[str, bytes]:
    before_name = parsed["before_name"]
    after_name = parsed["after_name"]
    payload_text = {
        "TASK.md": parsed["task"],
        before_name: parsed["before"],
        after_name: parsed["after"],
        "changes.diff": parsed["diff"],
        "performance.md": performance_markdown(parsed),
    }
    payload = {name: value.encode("utf-8") for name, value in payload_text.items()}
    roles = {
        "TASK.md": ("task", "generated"),
        before_name: ("before-code", parsed["evidence_mode"]),
        after_name: ("after-code", parsed["evidence_mode"]),
        "changes.diff": ("unified-diff", "generated"),
        "performance.md": ("performance", "generated"),
    }
    file_rows = []
    for name in sorted(payload):
        role, mode = roles[name]
        entry = {
            "local_path": name,
            "role": role,
            "mode": mode,
            "size": len(payload[name]),
            "sha256": sha256_bytes(payload[name]),
        }
        if name in {before_name, after_name}:
            entry["normalization"] = parsed["evidence_mode"]
        file_rows.append(entry)
    provenance = {
        "source_kind": "optimization-trace",
        "logical_run_id": logical_run_id,
        "imported_evidence_sha256": parsed["evidence_sha256"],
        "imported_manifest_row_sha256": manifest_sha,
        "receipt_date": "unknown",
        "receipt_date_policy": RECEIPT_DATE_POLICY,
        "evidence_limitations": limitations,
        "files": file_rows,
    }
    payload["PROVENANCE.yaml"] = yaml_text(provenance).encode("utf-8")
    return {f"{artifact_dir}/{name}": content for name, content in payload.items()}


def safe_evidence_path(root: Path, raw_path: object) -> Path:
    if not isinstance(raw_path, str) or not raw_path:
        raise ImportFailure("manifest evidence_path must be a non-empty string")
    logical = PurePosixPath(raw_path)
    if logical.is_absolute() or ".." in logical.parts:
        raise ImportFailure("manifest evidence_path must be a contained relative path")
    candidate = root.joinpath(*logical.parts)
    try:
        resolved = candidate.resolve(strict=True)
    except OSError as exc:
        raise ImportFailure("manifest evidence file is missing or unreadable") from exc
    if root != resolved and root not in resolved.parents:
        raise ImportFailure("manifest evidence path escapes the input root")
    if not resolved.is_file():
        raise ImportFailure("manifest evidence path is not a regular file")
    return resolved


def build_import(input_root: Path, repo_root: Path = REPO_ROOT) -> tuple[dict[str, bytes], list[dict], dict]:
    input_root = input_root.resolve(strict=True)
    repo_root = repo_root.resolve(strict=True)
    if input_root == repo_root or repo_root in input_root.parents or input_root in repo_root.parents:
        raise ImportFailure("input root and KernelWiki root must be separate trees")
    index_path = input_root / "index.jsonl"
    if not index_path.is_file():
        raise ImportFailure("input root does not contain a readable index.jsonl")
    index_raw = index_path.read_bytes()
    rows = []
    for number, line in enumerate(index_raw.decode("utf-8").splitlines(), 1):
        try:
            row = json.loads(line)
        except json.JSONDecodeError as exc:
            raise ImportFailure(f"index.jsonl line {number} is invalid JSON") from exc
        if not isinstance(row, dict):
            raise ImportFailure(f"index.jsonl line {number} is not an object")
        rows.append(row)

    artifacts: dict[str, bytes] = {}
    ledger = []
    input_snapshots: dict[Path, str] = {index_path: sha256_bytes(index_raw)}
    exact_targets: dict[tuple[str, str, str], dict] = {}
    semantic_targets: defaultdict[tuple[str, str], list[str]] = defaultdict(list)
    accepted_rows = []
    family_records: defaultdict[str, list[dict]] = defaultdict(list)
    manifest_occurrences = Counter()

    for ordinal, row in enumerate(rows, 1):
        manifest_json = canonical_json(row)
        manifest_sha = sha256_bytes(manifest_json.encode("utf-8"))
        occurrence = manifest_occurrences[manifest_sha]
        manifest_occurrences[manifest_sha] += 1
        input_identity = sha256_bytes(f"{manifest_json}\0{occurrence}".encode("utf-8"))
        input_id = f"trace-input-{input_identity[:20]}"
        base_ledger = {
            "input_id": input_id,
            "manifest_row_sha256": manifest_sha,
            "task_family": row.get("task_family", "unknown"),
        }
        if row.get("status") != "verified_faster":
            ledger.append({**base_ledger, "input_evidence_sha256": None, "disposition": "rejected", "reason_code": "status_not_verified_faster"})
            continue
        try:
            evidence_path = safe_evidence_path(input_root, row.get("evidence_path"))
            raw = evidence_path.read_bytes()
        except (ImportFailure, OSError):
            ledger.append({**base_ledger, "input_evidence_sha256": None, "disposition": "rejected", "reason_code": "evidence_file_unavailable"})
            continue
        input_snapshots[evidence_path] = sha256_bytes(raw)
        normalized, _ = normalized_text(raw)
        evidence_sha = sha256_bytes(normalized.encode("utf-8"))
        parsed, reason = parse_evidence(row, raw)
        if reason:
            ledger.append(
                {
                    **base_ledger,
                    "input_evidence_sha256": evidence_sha,
                    "disposition": "rejected",
                    "reason_code": reason,
                }
            )
            continue
        assert parsed is not None
        exact_key = (
            parsed["evidence_sha256"],
            sha256_bytes(parsed["before"].encode("utf-8")),
            sha256_bytes(parsed["after"].encode("utf-8")),
        )
        if exact_key in exact_targets:
            target = exact_targets[exact_key]
            ledger.append(
                {
                    **base_ledger,
                    "input_evidence_sha256": evidence_sha,
                    "disposition": "duplicate",
                    "reason_code": "exact_evidence_and_code_duplicate",
                    "canonical_input_id": target["input_id"],
                    "canonical_source_id": target["source_id"],
                    "canonical_wiki_id": target["wiki_id"],
                    "canonical_experiment_id": target["experiment_id"],
                    "canonical_artifact_path": target["artifact_path"],
                }
            )
            continue

        family = row["task_family"]
        logical_run_id, experiment_id = logical_ids(row, parsed, manifest_sha)
        source_id, wiki_id = family_page_ids(family)
        artifact_dir = f"artifacts/experiments/{family}/{experiment_id}"
        limitations = evidence_limitations(row, parsed)
        semantic_key = (family, sha256_bytes(parsed["after"].encode("utf-8")))
        semantic_duplicates = list(semantic_targets[semantic_key])
        semantic_targets[semantic_key].append(experiment_id)
        entry = {
            **base_ledger,
            "input_evidence_sha256": evidence_sha,
            "disposition": "accepted",
            "reason_code": "accepted_verified_pair",
            "experiment_id": experiment_id,
            "source_id": source_id,
            "wiki_id": wiki_id,
            "artifact_path": artifact_dir,
        }
        if semantic_duplicates:
            entry["semantic_duplicate_candidates"] = semantic_duplicates
        ledger.append(entry)
        exact_targets[exact_key] = {
            "input_id": input_id,
            "source_id": source_id,
            "wiki_id": wiki_id,
            "experiment_id": experiment_id,
            "artifact_path": artifact_dir,
        }
        artifacts.update(bundle_files(row, parsed, logical_run_id, source_id, wiki_id, manifest_sha, artifact_dir, limitations))
        record = {
            "row": row,
            "parsed": parsed,
            "logical_run_id": logical_run_id,
            "experiment_id": experiment_id,
            "manifest_sha": manifest_sha,
            "artifact_dir": artifact_dir,
            "limitations": limitations,
        }
        family_records[family].append(record)
        accepted_rows.append(record)

    for family, records in sorted(family_records.items()):
        slug = family.replace("_", "-")
        artifacts[f"sources/experiments/{family}.md"] = family_source_page(
            family, records
        ).encode("utf-8")
        artifacts[f"wiki/kernels/kernel-trace-{slug}.md"] = family_wiki_page(
            family, records
        ).encode("utf-8")

    ledger.sort(key=lambda item: item["input_id"])
    artifacts[str(LEDGER_PATH)] = (
        "".join(json.dumps(item, ensure_ascii=False, sort_keys=True) + "\n" for item in ledger)
    ).encode("utf-8")

    # Re-read every authoritative input before permitting a write phase.
    for path, digest in input_snapshots.items():
        if sha256_bytes(path.read_bytes()) != digest:
            raise ImportFailure("input changed while the import was being prepared")

    dispositions = Counter(item["disposition"] for item in ledger)
    reasons = Counter(item["reason_code"] for item in ledger)
    families = defaultdict(Counter)
    architectures = Counter()
    languages = Counter()
    techniques = Counter()
    for item in ledger:
        families[item["task_family"]][item["disposition"]] += 1
    for record in accepted_rows:
        parsed = record["parsed"]
        architectures.update(parsed["architectures"])
        languages.update(parsed["languages"])
        techniques.update(parsed["techniques"])
    summary = {
        "total_rows": len(rows),
        "dispositions": dict(sorted(dispositions.items())),
        "reasons": dict(sorted(reasons.items())),
        "families": {key: dict(sorted(value.items())) for key, value in sorted(families.items())},
        "architectures": dict(sorted(architectures.items())),
        "languages": dict(sorted(languages.items())),
        "techniques": dict(sorted(techniques.items())),
        "generated_files": len(artifacts),
    }
    return artifacts, ledger, summary


def importer_owned_files(repo_root: Path) -> set[Path]:
    owned = set()
    source_root = repo_root / "sources" / "experiments"
    if source_root.is_dir():
        owned.update(path for path in source_root.rglob("*.md") if path.is_file() or path.is_symlink())
    wiki_root = repo_root / "wiki" / "kernels"
    if wiki_root.is_dir():
        owned.update(path for path in wiki_root.glob("kernel-trace-*.md") if path.is_file() or path.is_symlink())
    artifact_root = repo_root / "artifacts" / "experiments"
    if artifact_root.is_dir():
        owned.update(path for path in artifact_root.rglob("*") if path.is_file() or path.is_symlink())
    return owned


def write_atomic(repo_root: Path, artifacts: dict[str, bytes], force: bool) -> tuple[int, int, int]:
    repo_root = repo_root.resolve(strict=True)
    changed = 0
    unchanged = 0
    conflicts = []
    expected_paths = {(repo_root / rel).resolve() for rel in artifacts}
    stale = sorted(importer_owned_files(repo_root) - expected_paths)
    if stale and not force:
        conflicts.extend(
            f"{path.relative_to(repo_root)} is stale importer-owned output (use --force)"
            for path in stale
        )
    for rel, content in sorted(artifacts.items()):
        target = repo_root / rel
        if target.exists():
            if not target.is_file():
                conflicts.append(f"{rel} exists and is not a file")
            elif target.read_bytes() == content:
                unchanged += 1
            elif not force:
                conflicts.append(f"{rel} exists with different content (use --force)")
    if conflicts:
        raise ImportFailure("\n".join(conflicts))

    stage = Path(tempfile.mkdtemp(prefix=".trace-import-stage-", dir=repo_root))
    try:
        for rel, content in sorted(artifacts.items()):
            staged = stage / rel
            staged.parent.mkdir(parents=True, exist_ok=True)
            staged.write_bytes(content)
        for rel, content in sorted(artifacts.items()):
            target = repo_root / rel
            if target.is_file() and target.read_bytes() == content:
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            staged = stage / rel
            temporary = target.with_name(f".{target.name}.import-{os.getpid()}")
            shutil.copyfile(staged, temporary)
            os.replace(temporary, target)
            changed += 1
    finally:
        shutil.rmtree(stage, ignore_errors=True)
    removed = 0
    if force:
        for path in stale:
            if path.is_file() or path.is_symlink():
                path.unlink()
                removed += 1
        for root_name in ("sources/experiments", "artifacts/experiments"):
            root = repo_root / root_name
            if root.is_dir():
                for directory in sorted((path for path in root.rglob("*") if path.is_dir()), reverse=True):
                    try:
                        directory.rmdir()
                    except OSError:
                        pass
    return changed, unchanged, removed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--input-root", required=True, type=Path, help="Read-only trace evidence root")
    parser.add_argument("--dry-run", action="store_true", help="Validate and report dispositions without writing")
    parser.add_argument("--force", action="store_true", help="Replace importer-owned files whose bytes differ")
    args = parser.parse_args()
    try:
        artifacts, _ledger, summary = build_import(args.input_root, REPO_ROOT)
        print(json.dumps(summary, ensure_ascii=False, indent=2, sort_keys=True))
        if args.dry_run:
            print("Dry run: no files written.")
            return 0
        changed, unchanged, removed = write_atomic(REPO_ROOT, artifacts, args.force)
        print(
            f"Import complete: {changed} file(s) written, {unchanged} already byte-identical, "
            f"{removed} stale importer-owned file(s) removed."
        )
        return 0
    except (ImportFailure, OSError, UnicodeDecodeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
