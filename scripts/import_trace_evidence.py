    lower = text.lower()
    patterns = {
        "tcgen05": r"tcgen05",
        "tmem": r"\btmem\b|tensor memory",
        "tma": r"\btma\b|tensor memory accelerator",
        "wgmma": r"\bwgmma\b",
        "nvfp4": r"\bnvfp4\b",
        "fp8": r"\bfp8\b",
        "fp4": r"\bfp4\b",
        "mbarrier": r"\bmbarrier\b",
        "ldmatrix": r"\bldmatrix\b",
        "stmatrix": r"\bstmatrix\b",
        "2sm-cooperative": r"\b2[- ]sm\b|two[- ]sm|cta_group::2",
        "pdl": r"programmatic dependent launch|\bpdl\b",
    }
    return [name for name, pattern in patterns.items() if re.search(pattern, lower)]


