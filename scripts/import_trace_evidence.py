def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def canonical_json(value) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def normalized_text(raw: bytes) -> tuple[str, str]:
    text = raw.decode("utf-8")
    mode = "copied-verbatim"
    if "\r" in text:
        text = text.replace("\r\n", "\n").replace("\r", "\n")
        mode = "newline-normalized"
    return text, mode


def yaml_text(value) -> str:
    return yaml.safe_dump(
        value,
        allow_unicode=True,
        default_flow_style=False,
        sort_keys=False,
        width=1000,
    )


def frontmatter(value) -> str:
    return f"---\n{yaml_text(value)}---\n\n"


def section(text: str, heading: str) -> str | None:
    match = re.search(rf"^## {re.escape(heading)}\s*$", text, re.MULTILINE)
    if not match:
        return None
    start = match.end()
    end = re.search(r"^## ", text[start:], re.MULTILINE)
    return text[start : start + (end.start() if end else len(text) - start)]


def fenced_section(text: str, heading: str) -> tuple[str | None, str | None]:
    block = section(text, heading)
    if block is None:
        return None, None
    match = re.search(r"^```([^\n]*)\n(.*?)^```\s*$", block, re.MULTILINE | re.DOTALL)
    if not match:
        return None, None
    return match.group(1).strip(), match.group(2)


def task_section(text: str) -> str | None:
    task = section(text, "Task")
    if task is None:
        return None
    # The task may contain level-two headings; section() therefore stops early.
    # Parse from the original document through the enclosing details block.
    start = re.search(r"^## Task\s*$", text, re.MULTILINE)
    if not start:
        return None
    tail = text[start.end() :]
    match = re.search(
        r"^(?P<fence>`{3,})markdown\n(.*?)^(?P=fence)\n\s*</details>",
        tail,
        re.MULTILINE | re.DOTALL,
    )
    return match.group(2) if match else None


def parse_metadata(text: str) -> dict[str, str]:
    block = section(text, "Metadata") or ""
    metadata = {}
    for line in block.splitlines():
        match = re.match(r"^\|\s*([^|]+?)\s*\|\s*(.*?)\s*\|$", line)
        if not match or match.group(1).strip() in {"Field", "---"}:
            continue
        value = match.group(2).strip()
        if value.startswith("`") and value.endswith("`"):
            value = value[1:-1]
        metadata[match.group(1).strip()] = value
    return metadata


def trim_diff(value: str) -> list[str]:
    lines = value.splitlines()
    while lines and not lines[-1].strip():
        lines.pop()
    return lines


def generated_diff(
    before: str,
    after: str,
    logical_name: str | None = None,
    *,
    before_name: str | None = None,
    after_name: str | None = None,
) -> str:
    before_lines = before.splitlines(keepends=True)
    after_lines = after.splitlines(keepends=True)
    diff = "".join(
        difflib.unified_diff(
            before_lines,
            after_lines,
            fromfile=before_name or f"before/{logical_name}",
            tofile=after_name or f"after/{logical_name}",
        )
    )
    if diff and not diff.endswith("\n"):
        diff += "\n"
    return diff


def number_present(text: str, value: str) -> bool:
    expected = float(value)
    return any(
        abs(float(candidate) - expected) <= max(1e-12, abs(expected) * 1e-12)
        for candidate in re.findall(r"(?<![0-9.])([0-9]+(?:\.[0-9]+)?)(?![0-9.])", text)
    )


def clean_excerpt(trace: str) -> str | None:
    trace = trace.strip()
    table = trace.find(r"\|")
    if table >= 0:
        trace = trace[table:]
    else:
        trace = re.sub(r"^[^\s]+/[^:]+:\d+:\s*", "", trace)
    if TRACE_LOCATOR_RE.search(trace):
        return None
    return trace if trace else None


def _percent(interp: str) -> float | None:
    match = re.search(r"([0-9]+(?:\.[0-9]+)?)%", interp)
    return float(match.group(1)) if match else None


def parse_comparison(heading: str, interp: str, trace: str) -> dict | None:
    if any(marker in trace for marker in KNOWN_CONTAMINATION):
        return None
    lowered = trace.lower()
    if (
        "regress" in lowered
        or "falsifying" in lowered
        or "no code change lands" in lowered
        or "sibling" in lowered
        or "despite" in lowered
        or re.search(r"all-workload geomean was\s+0\.", lowered)
    ):
        return None
    excerpt = clean_excerpt(trace)
    if not excerpt:
        return None

    metric = None
    unit = None
    before = None
    after = None

    latency = re.search(
        r"Latency decreases from\s+([0-9]+(?:\.[0-9]+)?)\s*([uµ]?s|ms|s)\s+"
        r"to\s+([0-9]+(?:\.[0-9]+)?)\s*([uµ]?s|ms|s)",
        interp,
        re.IGNORECASE,
    )
    if latency:
        before, unit, after, after_unit = latency.groups()
        if unit.replace("µ", "u").lower() != after_unit.replace("µ", "u").lower():
            return None
        metric = "latency"
    else:
        score = re.search(
            r"performance metric increases from\s+([0-9]+(?:\.[0-9]+)?)\s+to\s+"
            r"([0-9]+(?:\.[0-9]+)?)",
            interp,
            re.IGNORECASE,
        )
        if score:
            before, after = score.groups()
            metric, unit = "score", "ratio"

    if before is None and "inherited-to-selected" in interp.lower():
        values = re.findall(r"([0-9]+(?:\.[0-9]+)?)\s*([uµ]?s|ms|s)\b", excerpt)
        target_percent = _percent(interp)
        candidates = []
        for left_index, (left, left_unit) in enumerate(values):
            for right, right_unit in values[left_index + 1 :]:
                if left_unit.replace("µ", "u").lower() != right_unit.replace("µ", "u").lower():
                    continue
                left_value, right_value = float(left), float(right)
                if left_value <= right_value:
                    continue
                actual_percent = (left_value - right_value) / left_value * 100
                error = abs(actual_percent - target_percent) if target_percent is not None else 0
                candidates.append((error, left, right, left_unit))
        if candidates:
            error, before, after, unit = min(candidates, key=lambda value: value[0])
            if target_percent is None or error <= max(0.08, target_percent * 0.08):
                metric = "latency"
            else:
                before = after = unit = None

    if before is None:
        old_new = re.search(
            r"old\s*=\s*([0-9]+(?:\.[0-9]+)?)\s*([uµ]?s|ms|s).*?"
            r"new\s*=\s*([0-9]+(?:\.[0-9]+)?)\s*([uµ]?s|ms|s)",
            excerpt,
            re.IGNORECASE,
        )
        if old_new:
            before, unit, after, after_unit = old_new.groups()
            if unit.replace("µ", "u").lower() != after_unit.replace("µ", "u").lower():
                return None
            metric = "latency"

    if before is None:
        return None
    if not number_present(excerpt, before) or not number_present(excerpt, after):
        return None

    before_value = float(before)
    after_value = float(after)
    if metric == "latency" and not before_value > after_value:
        return None
    if metric == "score" and not after_value > before_value:
        return None
    ratio = before_value / after_value if metric == "latency" else after_value / before_value
    if ratio <= 1 or ratio > 20:
        return None
    return {
        "heading": heading,
        "metric": metric,
        "unit": unit.replace("µ", "u"),
        "before_value": before_value,
        "after_value": after_value,
        "value": after_value,
        "improvement_percent": _percent(interp),
        "interpretation": interp.strip(),
        "excerpt": excerpt,
    }


def parse_performance(text: str) -> tuple[list[dict], int]:
    block = section(text, "Verified performance evidence")
    if block is None:
        return [], 0
    entries = []
    raw_count = 0
    pattern = re.compile(r"^###\s+(.+?)\s*$\n(.*?)(?=^###\s+|\Z)", re.MULTILINE | re.DOTALL)
    for match in pattern.finditer(block):
        raw_count += 1
        entry = match.group(2)
        interp_match = re.search(r"^- Interpretation:\s*(.+)$", entry, re.MULTILINE)
        trace_match = re.search(r"^- Trace text:\s*(.+)$", entry, re.MULTILINE)
        if not interp_match or not trace_match:
            continue
        parsed = parse_comparison(match.group(1), interp_match.group(1), trace_match.group(1))
        if parsed:
            entries.append(parsed)
    return entries, raw_count


def detect_architectures(title: str) -> list[str]:
    value = title.lower()
    if "b300" in value or "sm103" in value:
        return ["sm103"]
    if "b200" in value or "sm100" in value:
        return ["sm100"]
    if "hopper" in value or "h100" in value or "sm90" in value:
        return ["sm90"]
    if "blackwell" in value:
        return ["blackwell"]
    return []


def detect_languages(title: str, code: str) -> list[str]:
    value = f"{title}\n{code}".lower()
    if "triton" in title.lower():
        return ["triton"]
    if "cuda c++" in title.lower() or "cuda-c++" in title.lower():
        return ["cuda-cpp"]
    if "cute-dsl" in title.lower() or "cutlass.cute" in value or "import cute" in value:
        return ["cute-dsl"]
    if "triton" in value and "@triton" in value:
        return ["triton"]
    return ["python"]


def detect_dtype(title: str, task: str) -> str:
    value = f"{title}\n{task}".lower()
    found = []
    for token in ("fp8", "fp4", "bf16", "fp16", "float32"):
        if token in value:
            found.append(token)
    return "/".join(found[:2]) if found else "not stated"


